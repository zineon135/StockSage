import { AlertTriangle, BookOpenCheck, ExternalLink, Lightbulb, ShieldAlert } from 'lucide-react'
import type { Point, Source } from '../../lib/types'
import { dateTime } from '../../lib/format'
import { cx } from './primitives'

const FLAG_TEXT: Record<string, string> = {
  unverified_number: 'Contains a number Stock Sage could not match to retrieved data',
  unsourced_fact_downgraded: 'Presented as interpretation because no source was cited',
  removed_unknown_citation: 'An invalid citation was removed',
  guarantee_language: 'Uses certainty language — outcomes are never guaranteed',
}

export function CitationChips({ ids, sources }: { ids: string[]; sources: Source[] }) {
  if (!ids.length) return null
  return (
    <span className="ml-1 inline-flex flex-wrap gap-1 align-middle">
      {ids.map((id) => {
        const s = sources.find((x) => x.id === id)
        const title = s ? `${s.title} — ${s.publisher ?? s.provider}${s.timestamp ? ` · ${dateTime(s.timestamp)}` : ''}` : id
        return s?.url ? (
          <a key={id} href={s.url} target="_blank" rel="noopener noreferrer" title={title}
            className="num rounded-md border border-info/30 bg-info-soft px-1 text-[10px] font-medium text-info hover:bg-info/20">{id}</a>
        ) : (
          <span key={id} title={title} className="num rounded-md border border-line-strong bg-white/12 px-1 text-[10px] font-medium text-ink-2">{id}</span>
        )
      })}
    </span>
  )
}

export function PointItem({ p, sources }: { p: Point; sources: Source[] }) {
  const fact = p.type === 'fact'
  return (
    <li className="flex gap-2.5 text-[13px] leading-relaxed text-ink-2">
      <span className={cx('mt-0.5 shrink-0', fact ? 'text-info' : 'text-warn')} title={fact ? 'Fact from a cited source' : 'Analytical interpretation'}>
        {fact ? <BookOpenCheck size={14} /> : <Lightbulb size={14} />}
      </span>
      <span>
        {p.text}
        <CitationChips ids={p.source_ids} sources={sources} />
        {p.flags.filter((f) => FLAG_TEXT[f]).map((f) => (
          <span key={f} className="ml-1.5 inline-flex items-center gap-1 text-[11px] text-warn" title={FLAG_TEXT[f]}>
            <AlertTriangle size={11} /> {FLAG_TEXT[f]}
          </span>
        ))}
      </span>
    </li>
  )
}

export function FactLegend() {
  return (
    <div className="flex flex-wrap items-center gap-3 text-[11px] text-muted">
      <span className="inline-flex items-center gap-1"><BookOpenCheck size={12} className="text-info" /> Fact (cited source)</span>
      <span className="inline-flex items-center gap-1"><Lightbulb size={12} className="text-warn" /> Interpretation</span>
    </div>
  )
}

/** Inline [Q1] style citations inside free text become clickable chips. */
export function CitedText({ text, sources }: { text: string; sources: Source[] }) {
  const parts = text.split(/(\[[A-Z]\d{1,2}(?:\s*,\s*[A-Z]\d{1,2})*\])/g)
  return (
    <>
      {parts.map((part, i) => {
        const m = part.match(/^\[(.*)\]$/)
        if (!m) return <span key={i}>{part}</span>
        return <CitationChips key={i} ids={m[1].split(',').map((s) => s.trim())} sources={sources} />
      })}
    </>
  )
}

export function SourceList({ sources, className }: { sources: Source[]; className?: string }) {
  if (!sources.length) return null
  return (
    <div className={className}>
      <div className="mb-2 text-[11px] font-semibold uppercase tracking-wide text-muted">Sources used</div>
      <ol className="space-y-1.5">
        {sources.map((s) => (
          <li key={s.id} className="flex gap-2 text-xs">
            <span className="num w-7 shrink-0 text-ink-2">{s.id}</span>
            <span className="min-w-0 text-muted">
              {s.url ? (
                <a href={s.url} target="_blank" rel="noopener noreferrer" className="text-ink-2 hover:text-info hover:underline">
                  {s.title} <ExternalLink size={10} className="inline" />
                </a>
              ) : <span className="text-ink-2">{s.title}</span>}
              <span className="block text-[11px] text-faint">
                {s.publisher ? `${s.publisher} via ${s.provider}` : s.provider}
                {s.timestamp && ` · data time ${dateTime(s.timestamp)}`}
                {` · retrieved ${dateTime(s.retrieved_at)}`}
                {s.stale && <span className="text-warn"> · stale</span>}
              </span>
            </span>
          </li>
        ))}
      </ol>
    </div>
  )
}

export function AIDisclaimer({ text, model }: { text: string; model?: string }) {
  return (
    <div className="flex items-start gap-2 rounded-xl border border-line bg-panel-2 px-3 py-2 text-[11px] text-muted">
      <ShieldAlert size={13} className="mt-px shrink-0" />
      <span>{text}{model && <> · Generated by {model} from data retrieved by Stock Sage.</>}</span>
    </div>
  )
}
